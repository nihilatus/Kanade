#!/usr/bin/env python3
"""Convert Augustine human premapping CSV → machine CSV and firmware include."""

from __future__ import annotations

import csv
import io
import re
import sys
from collections import defaultdict
from pathlib import Path

import recipe

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "esp32-jis-chordboard-premapping.csv"
OUT = ROOT / "data" / "chord_map.machine.csv"
INC = ROOT / "include" / "chord_map.inc"

KEY_ORDER = [
    "LL",
    "LU",
    "LR",
    "LD",
    "LT0",
    "LT1",
    "LT2",
    "RL",
    "RU",
    "RR",
    "RD",
    "RT0",
    "RT1",
    "RT2",
]
KEY_RANK = {k: i for i, k in enumerate(KEY_ORDER)}

HUMAN_COLUMNS = [
    "section",
    "label",
    "output",
    "left_fingers",
    "right_fingers",
    "left_thumb",
    "right_thumb",
    "repeat",
]


def c_string(text: str) -> str:
    """UTF-8 C string literal. Firmware source is compiled as UTF-8."""
    out = ['"']
    for ch in text:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif o < 32 or o == 127:
            out.append(f"\\x{o:02x}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def mask_of(field: str) -> int:
    if not field or not field.strip():
        return 0
    mask = 0
    for part in field.split("+"):
        tok = part.strip()
        if not tok:
            continue
        if tok not in KEY_RANK:
            raise ValueError(f"Unknown key in machine row: {tok!r}")
        mask |= 1 << KEY_RANK[tok]
    return mask


def write_firmware_include(rows: list[dict[str, str]]) -> None:
    """Bit i matches ButtonId i / KEY_ORDER[i]. Included inside kChordMap[]."""
    lines = [
        "// Generated by tools/build_chord_map_machine.py — do not edit.",
        "// Rebuild: python tools/build_chord_map_machine.py",
        "// Columns: id, required mask, optional mask, kana, output, repeat.",
    ]
    for row in rows:
        required = mask_of(row["keys_required"])
        optional = mask_of(row["keys_optional"])
        repeat = "true" if row["repeat"] == "allow" else "false"
        lines.append(
            "    {%s, 0x%04Xu, 0x%04Xu, %s, %s, %s},"
            % (
                row["id"],
                required,
                optional,
                c_string(row["kana"]),
                c_string(row["output"]),
                repeat,
            )
        )
    INC.parent.mkdir(parents=True, exist_ok=True)
    with INC.open("w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def sort_keys(keys: set[str]) -> list[str]:
    return sorted(keys, key=lambda k: KEY_RANK.get(k, 1000 + hash(k)))


class HumanCsvError(Exception):
    """The human CSV cannot be read as a table. Machine outputs stay untouched."""


def human_csv_text() -> str:
    raw = SRC.read_bytes()
    if raw.startswith((b"\xff\xfe", b"\xfe\xff")):
        raise HumanCsvError(
            "Human CSV is UTF-16. In Excel, save as CSV UTF-8 (comma delimited)."
        )
    if not raw.startswith(b"\xef\xbb\xbf"):
        raise HumanCsvError(
            "Human CSV must start with a UTF-8 BOM so Excel opens it as UTF-8."
        )
    try:
        return raw.decode("utf-8-sig")
    except UnicodeDecodeError as exc:
        raise HumanCsvError(f"Human CSV is not valid UTF-8: {exc}") from exc


def normalize_section(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def iter_human_rows():
    """Yield (lineno, eight stripped cells) from the human CSV."""
    text = human_csv_text()
    reader = csv.DictReader(io.StringIO(text), restkey="_extra")
    if list(reader.fieldnames or []) != HUMAN_COLUMNS:
        found = reader.fieldnames
        raise HumanCsvError(
            "Human CSV header must be "
            + ",".join(HUMAN_COLUMNS)
            + f", got {found!r}"
        )
    for lineno, row in enumerate(reader, start=2):
        extra = row.get("_extra")
        if extra:
            raise ValueError(f"line {lineno}: extra column {extra!r}")
        cells: list[str] = []
        for name in HUMAN_COLUMNS:
            value = row.get(name)
            if value is None:
                raise ValueError(f"line {lineno}: missing {name}")
            if "\n" in value or "\r" in value:
                raise ValueError(f"line {lineno}: {name} contains a newline")
            cells.append(value.strip())
        yield lineno, cells


def parse_key_field(field: str) -> tuple[set[str], set[str]]:
    """Return (required, optional) key tokens from one CSV cell."""
    required: set[str] = set()
    optional: set[str] = set()
    if not field or not field.strip():
        return required, optional
    for part in field.split("+"):
        tok = part.strip()
        if not tok:
            continue
        optional_flag = tok.startswith("(") and tok.endswith(")")
        if optional_flag:
            inner = tok[1:-1].strip()
            if inner not in KEY_RANK:
                raise ValueError(f"Unknown optional key token: {tok!r}")
            optional.add(inner)
            continue
        if tok not in KEY_RANK:
            raise ValueError(f"Unknown key token: {tok!r} in field {field!r}")
        required.add(tok)
    return required, optional


def main() -> int:
    rows_out: list[dict[str, str]] = []
    current_category = ""
    omitted_empty = 0
    parse_errors: list[str] = []

    try:
        human_rows = list(iter_human_rows())
    except HumanCsvError as exc:
        print(exc)
        return 1
    except ValueError as exc:
        print(exc)
        return 1

    for lineno, cells in human_rows:
        section, label, output, left_f, right_f, left_t, right_t, repeat_cell = cells
        if section:
            current_category = normalize_section(section)

        if not label and not output:
            omitted_empty += 1
            continue

        req: set[str] = set()
        opt: set[str] = set()
        try:
            for field in (left_f, right_f, left_t, right_t):
                r, o = parse_key_field(field)
                req |= r
                opt |= o
            # Tokens chord_parse_recipe would add_skip still send the rest
            # of the recipe on device. Reject them before they ship.
            reason = recipe.recipe_build_error(output)
            if reason:
                raise ValueError(reason)
            if repeat_cell not in ("allow", "no"):
                raise ValueError(
                    f"repeat must be allow or no, got {repeat_cell!r}"
                )
        except ValueError as e:
            parse_errors.append(f"line {lineno}: {e}")
            continue

        # Optional must not also be required
        opt -= req

        rows_out.append(
            {
                "id": str(len(rows_out) + 1),
                "kana": label,
                "output": output,
                "keys_required": "+".join(sort_keys(req)),
                "keys_optional": "+".join(sort_keys(opt)),
                "category": current_category,
                "repeat": repeat_cell,
            }
        )

    # Conflict report: identical (required, optional) with different outputs
    by_keys: dict[tuple[str, str], list[dict[str, str]]] = defaultdict(list)
    for r in rows_out:
        by_keys[(r["keys_required"], r["keys_optional"])].append(r)

    conflicts: list[str] = []
    soft_dups: list[str] = []
    for (req, opt), group in sorted(by_keys.items(), key=lambda x: int(x[1][0]["id"])):
        outputs = {g["output"] for g in group}
        if len(group) > 1 and len(outputs) > 1:
            conflicts.append(
                f"CONFLICT keys_required={req!r} keys_optional={opt!r}: "
                + "; ".join(f"id={g['id']} kana={g['kana']!r} output={g['output']!r}" for g in group)
            )
        elif len(group) > 1:
            soft_dups.append(
                f"DUP-SAME-OUTPUT keys_required={req!r} keys_optional={opt!r}: "
                + ", ".join(f"id={g['id']}" for g in group)
                + f" output={group[0]['output']!r}"
            )

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(
            f,
            lineterminator="\n",
            fieldnames=[
                "id",
                "kana",
                "output",
                "keys_required",
                "keys_optional",
                "category",
                "repeat",
            ],
        )
        writer.writeheader()
        writer.writerows(rows_out)

    write_firmware_include(rows_out)

    report = ROOT / "data" / "chord_map.machine.report.txt"
    with report.open("w", encoding="utf-8", newline="\n") as f:
        f.write(f"source: {SRC.name}\n")
        f.write(f"rows_written: {len(rows_out)}\n")
        f.write(f"omitted_empty_kana_and_output: {omitted_empty}\n")
        f.write(f"key_codes ({len(KEY_ORDER)}): {', '.join(KEY_ORDER)}\n")
        f.write(f"parse_errors: {len(parse_errors)}\n")
        for e in parse_errors:
            f.write(f"  {e}\n")
        f.write(f"true_conflicts: {len(conflicts)}\n")
        for c in conflicts:
            f.write(f"  {c}\n")
        f.write(f"same_keys_same_output_dups: {len(soft_dups)}\n")
        for d in soft_dups:
            f.write(f"  {d}\n")

    print(f"Wrote {OUT} ({len(rows_out)} rows)")
    print(f"Wrote {INC}")
    print(f"Omitted empty: {omitted_empty}")
    print(f"Conflicts: {len(conflicts)}")
    print(f"Same-output dups: {len(soft_dups)}")
    print(f"Parse errors: {len(parse_errors)}")
    for c in conflicts:
        print(c)
    for e in parse_errors:
        print(e)

    if parse_errors or conflicts:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
